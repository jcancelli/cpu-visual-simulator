/** Source or destination for a read/write {@link Bus} operation */
export enum Register {
	// CPU
	PROGRAM_COUNTER,
	INSTRUCTION_REGISTER,
	INSTRUCTION_REGISTER_OPCODE,
	INSTRUCTION_REGISTER_OPERAND,
	DECODER,
	CONTROL_UNIT,
	MUX,
	ALU_OPERAND_1,
	ALU_OPERAND_2,
	ALU_OPERATION,
	ALU_RESULT,
	ALU_STATUS_WORD,
	ACCUMULATOR,
	STATUS_WORD,
	// Memory
	MEMORY_ADDRESS,
	MEMORY_OPERATION,
	MEMORY_DATA,
}

/** ID of a {@link Bus} */
export enum BusID {
	DATA,
	ADDRESS,
	MEMORY_CONTROL,
	OPCODE_DECODER,
	MUX_ALU,
	MUX_CONTROL,
	ALU_CONTROL,
	STATUS_WORD,
	ALU_ACCUMULATOR,
}
